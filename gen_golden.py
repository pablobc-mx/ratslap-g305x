#!/usr/bin/env python3
"""Generate golden.h for ratslap-g305x.

Builds golden on-board profile sectors for the v6 layout (profile format 7,
the G305 X family) and the v1 layout (formats 1-5, the original G305), plus
the initial profile-directory sectors used by the mock-hidraw integration
test. CRCs are computed with binascii.crc_hqx (poly 0x1021, init 0xFFFF,
no reflection) — an implementation independent of the C code under test.

Usage: python3 gen_golden.py > golden.h
"""
import binascii

SEC = 256


def crc(data: bytes) -> int:
    return binascii.crc_hqx(data, 0xFFFF)


# sanity: canonical CRC-16/CCITT-FALSE check value
check = crc(b"123456789")
assert check == 0x29B1, f"crc_hqx sanity check failed: {check:#06x}"


def le16(v: int) -> bytes:
    return bytes([v & 0xFF, v >> 8])


def mouse(mask: int) -> bytes:
    return bytes([0x80, 0x01, mask >> 8, mask & 0xFF])


def fn(code: int) -> bytes:
    return bytes([0x90, code, 0x00, 0x00])


def finish(d: bytearray):
    c = crc(bytes(d[: SEC - 2]))
    d[SEC - 2] = c >> 8
    d[SEC - 1] = c & 0xFF
    return bytes(d), c


def v7(stages, default_idx, shift_idx, buttons, name):
    d = bytearray(b"\xff" * SEC)
    d[0x00] = 3  # wireless rate index (3 = 1000 Hz)
    d[0x01] = 3  # wired rate index
    d[0x02] = default_idx
    d[0x03] = shift_idx
    for i, (x, y, lod) in enumerate(stages):
        b = 0x04 + i * 5
        d[b:b + 2] = le16(x)
        d[b + 2:b + 4] = le16(y)
        d[b + 4] = lod
    # 0x1D..0x2B: angle snap + vendor bytes, carried through untouched
    d[0x20] = 0xAA
    d[0x21] = 0xBB
    d[0x22] = 0x00
    d[0x2C:0x2E] = le16(300)  # sleep timeout
    d[0x2E:0x30] = le16(600)  # power-off timeout
    for i, b in enumerate(buttons):
        d[0x30 + 4 * i: 0x34 + 4 * i] = b
    for i in range(6):  # G-shift bindings: all disabled
        d[0x70 + 4 * i: 0x74 + 4 * i] = b"\xff\xff\xff\xff"
    nm = name.encode("utf-16le")
    assert len(nm) <= 46
    d[0xA0: 0xA0 + 48] = nm + b"\x00" * (48 - len(nm))
    d[0xD0: 0xD0 + 44] = b"\x00" * 44  # 4 x 11-byte lighting records (off)
    return finish(d)


def v1(stages, default_idx, shift_idx, buttons, name):
    d = bytearray(b"\xff" * SEC)
    d[0x00] = 1  # rate byte: 1000/hz = 1 -> 1000 Hz (single byte)
    d[0x01] = default_idx
    d[0x02] = shift_idx
    for i, x in enumerate(stages):
        d[0x03 + 2 * i: 0x05 + 2 * i] = le16(x)
    d[0x11] = 0  # angle snap off
    d[0x1C:0x1E] = le16(300)
    d[0x1E:0x20] = le16(600)
    for i, b in enumerate(buttons):
        d[0x20 + 4 * i: 0x24 + 4 * i] = b
    for i in range(6):
        d[0x60 + 4 * i: 0x64 + 4 * i] = b"\xff\xff\xff\xff"
    nm = name.encode("utf-16le")
    d[0xA0: 0xA0 + 48] = nm + b"\x00" * (48 - len(nm))
    return finish(d)


def directory(entries):
    d = bytearray(b"\xff" * SEC)
    for i, (sec, en) in enumerate(entries):
        d[4 * i: 4 * i + 4] = bytes([sec >> 8, sec & 0xFF, 1 if en else 0, 0xFF])
    return finish(d)


user_buttons = [mouse(1), mouse(2), mouse(4), mouse(8), mouse(0x10), fn(0x07)]  # G6 = DPI Shift
rom_buttons = [mouse(1), mouse(2), mouse(4), mouse(8), mouse(0x10), fn(0x05)]  # G6 = DPI Cycle

gold_v7, crc_v7 = v7([(400, 400, 1), (800, 800, 1), (1600, 1600, 2),
                     (3200, 3200, 2), (6400, 6400, 0)], 1, 0, user_buttons, "Profile 1")
rom_v7, crc_rom = v7([(800, 800, 1), (1600, 1600, 1), (3200, 3200, 1)],
                     0, 0, rom_buttons, "Default")
# Owner-confirmed on a real G305 X: the factory ROM profile sector carries
# no valid CRC — the tool decodes it, but crc_ok() on it fails, and the
# write guard refuses to copy ROM raw bytes anywhere. OpenGMice likewise
# never writes ROM raw; mirror the factory bytes here.
rom_v7 = rom_v7[:-2] + b"\xff\xff"
gold_v1, crc_v1 = v1([400, 800, 1600, 3200, 6400], 1, 0, user_buttons, "Profile 1")
dir_user, crc_dir = directory([(1, True), (2, True)])
dir_rom, crc_romdir = directory([(0x101, True)])


def emit_array(name, data):
    print(f"static const uint8_t {name}[GOLDEN_SECTOR_SIZE] = {{")
    for i in range(0, SEC, 16):
        row = ", ".join(f"0x{b:02X}" for b in data[i:i + 16])
        print(f"    {row},")
    print("};")
    print()


print("/* Generated by gen_golden.py — do not edit by hand.")
print(" * CRC-CCITT (poly 0x1021, init 0xFFFF, no reflection) computed with")
print(" * binascii.crc_hqx, independent of the C code under test.")
print(" * Canonical check verified at generation time: crc(b\"123456789\") == 0x29B1.")
print(" */")
print("#ifndef RSLAP_GOLDEN_H")
print("#define RSLAP_GOLDEN_H")
print("#define GOLDEN_SECTOR_SIZE 256")
print(f"#define GOLDEN_V7_CRC 0x{crc_v7:04X}")
print(f"#define GOLDEN_V7_ROM_CRC 0x{crc_rom:04X}")
print(f"#define GOLDEN_V1_CRC 0x{crc_v1:04X}")
print(f"#define GOLDEN_DIR_CRC 0x{crc_dir:04X}")
print(f"#define GOLDEN_ROMDIR_CRC 0x{crc_romdir:04X}")
emit_array("GOLDEN_V7", gold_v7)
emit_array("GOLDEN_V7_ROM", rom_v7)
emit_array("GOLDEN_V1", gold_v1)
emit_array("GOLDEN_DIR", dir_user)
emit_array("GOLDEN_ROMDIR", dir_rom)
print("/* expected decode of GOLDEN_V7 (asserted by test_profile.c) */")
print("#define GOLDEN_V7_RATE 1000")
print("#define GOLDEN_V7_DEFAULT_IDX 1")
print("#define GOLDEN_V7_SHIFT_IDX 0")
print("#define GOLDEN_V7_N_STAGES 5")
print("#define GOLDEN_V7_PS 300")
print("#define GOLDEN_V7_PO 600")
print('#define GOLDEN_V7_NAME "Profile 1"')
print("/* expected decode of GOLDEN_V1 */")
print("#define GOLDEN_V1_RATE 1000")
print("#define GOLDEN_V1_DEFAULT_IDX 1")
print("#define GOLDEN_V1_N_STAGES 5")
print('#define GOLDEN_V1_NAME "Profile 1"')
print("#endif")
